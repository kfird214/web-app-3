export const levelById = id => LEVELS.find(l => l.id === id) || null;

// Documentation is cumulative: at level N the player can read everything up to N.
export function docsUpTo(levelId) {
    return LEVELS
        .filter(l => l.id <= levelId)
        .map(l => ({ level: l.id, name: l.name, entries: l.docs }));
}

export function taskText(level, session) {
    return level.task_of ? level.task_of(session) : (level.task || null);
}
