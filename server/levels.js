const queryKeys = q => Object.keys(q);
const isPlainObject = v => v !== null && typeof v === 'object' && !Array.isArray(v);

// Compares the request the player built against what the level expects.
// Returns { ok, hint } - hints say what is wrong without giving the answer away.
function expectRequest(target, spec) {
    if (target.method !== spec.method) {
        return { ok: false, hint: `This level is not asking for a ${target.method} request.` };
    }
    if (target.path !== spec.path) {
        return { ok: false, hint: `${target.path} is not the resource this level is about. Check the documentation.` };
    }
    const used = queryKeys(target.query);
    const expected = spec.query || {};
    const expectedKeys = Object.keys(expected);
    const sameQuery = used.length === expectedKeys.length
        && expectedKeys.every(k => String(target.query[k]) === String(expected[k]));
    if (!sameQuery) {
        return {
            ok: false,
            hint: expectedKeys.length === 0
                ? 'This request does not take a query string.'
                : 'The query string is not what this level asks for.',
        };
    }
    return { ok: true };
}

function needsJsonBody(target, what) {
    if (!isPlainObject(target.body)) {
        return { ok: false, hint: `This request needs a JSON body ${what}.` };
    }
    return { ok: true };
}

